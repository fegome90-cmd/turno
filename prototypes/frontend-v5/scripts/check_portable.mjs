// A DOM simulation of the built file, not a browser or visual verification.
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {parseHTML} from 'linkedom';
const html=await fs.readFile(new URL('../preview.html',import.meta.url),'utf8');
const script=html.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'one inline module must exist');
assert.doesNotMatch(script,/^import /m);
assert.doesNotMatch(html,/(?:src|href)="\.\//);
assert.doesNotMatch(html,/url\(['"]?\.\.\/assets\//);
assert.match(html,/viewport-fit=cover/);
const {window}=parseHTML(html);
window.innerWidth=390;
let focused=window.document.body;
Object.defineProperty(window.document,'activeElement',{configurable:true,get:()=>focused});
window.HTMLElement.prototype.focus=function(){if(!this.disabled)focused=this;};
window.HTMLElement.prototype.showModal=function(){this.open=true;this.setAttribute('open','');};
window.HTMLElement.prototype.close=function(){this.open=false;this.removeAttribute('open');};
globalThis.window=window;globalThis.document=window.document;
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const q=s=>window.document.querySelector(s);
const click=async s=>{assert.ok(q(s),s);q(s).focus();q(s).dispatchEvent(new window.Event('click',{bubbles:true}));await pause(2);};
const fill=(s,value)=>{q(s).value=value;q(s).dispatchEvent(new window.Event('input',{bubbles:true}));};
const submit=async()=>{q('#editor-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));await pause(500);};
await import('data:text/javascript;base64,'+Buffer.from(script).toString('base64'));
await pause(250);
assert.match(q('.greeting h1').textContent,/Hola, Demo/);
await click('[data-action="open-shift"]');await click('[data-action="toggle-inspector"]');
fill('#date','31/02/2026');await click('[data-action="close-inspector"]');await submit();
assert.equal(q('#modal #date').getAttribute('aria-invalid'),'true');
assert.equal(window.document.activeElement.id,'date');
await click('[data-action="close-inspector"]');fill('#body','Borrador de prueba portátil');
await click('[data-action="toggle-inspector"]');assert.equal(q('#modal #date').getAttribute('aria-invalid'),'true');
fill('#date','07/11/2026');assert.equal(q('#date').hasAttribute('aria-invalid'),false);
await click('[data-action="close-inspector"]');await submit();assert.match(q('#save-feedback').textContent,/Guardado/);
await click('[data-action="demo"]');await click('[data-action="simulate-conflict"]');
await click('[data-action="close-shift"]');await click('[data-action="confirm-close"]');await pause(500);
assert.match(q('#close-error').textContent,/Cerrar y archivar/);
assert.doesNotMatch(q('#close-error').textContent,/guardar|borrador/i);
await click('[data-action="confirm-close"]');await pause(500);assert.equal(q('#modal').open,false);
console.log('PASS: built HTML startup, greeting, mobile validation, error retention, correction, save, close conflict and retry; local assets embedded.');
console.log('LIMIT: Node/LinkeDOM only. No CSS rendering, native focus, real input, visual QA, browser or hardware.');
